#!/usr/bin/env python3
"""Generate and verify the exact Git-visible repository inventory.

The authority is Git tracked files plus non-ignored untracked files. The only
additional policy exclusion is the private _audit_workspace/** tree.
"""

from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
OUTPUT_PATH = ROOT / "CODEBASE_STRUCTURE.md"
WORKFLOW_PATH = ROOT / ".github" / "workflows" / "audit.yml"
WORKFLOW_COMMAND = "python3 -X utf8 build_scripts/manage_codebase_structure.py --check"
GIT_LS_FILES_ARGS = (
    "git", "ls-files", "--cached", "--others", "--exclude-standard", "-z",
)
AUDIT_PREFIX = "_audit_workspace/"


class InventoryError(ValueError):
    """Raised when the inventory cannot be represented exactly."""


def natural_component_key(value: str) -> tuple[tuple[object, ...], ...]:
    """Return a stable case-insensitive natural key with a stable tie break."""
    chunks: list[tuple[object, ...]] = []
    for token in re.split(r"(\d+)", value):
        if token.isdigit():
            chunks.append((0, int(token), len(token)))
        else:
            chunks.append((1, token.casefold(), token))
    return tuple(chunks)


def natural_path_key(path: str) -> tuple[tuple[tuple[object, ...], ...], ...]:
    return tuple(natural_component_key(part) for part in path.split("/"))


def normalize_inventory(paths: list[str], root: Path | None = None) -> list[str]:
    """Validate Git paths, apply the sole policy exclusion, and deduplicate."""
    normalized: list[str] = []
    seen: set[str] = set()
    for raw in paths:
        if not isinstance(raw, str) or not raw:
            raise InventoryError("Git inventory contains an empty or non-string path")
        if "\\" in raw:
            raise InventoryError(f"Git path is not POSIX-normalized: {raw!r}")
        path = raw.removeprefix("./")
        parts = path.split("/")
        if path.startswith("/") or any(part in {"", ".", ".."} for part in parts):
            raise InventoryError(f"unsafe or non-canonical Git path: {raw!r}")
        if path.startswith(AUDIT_PREFIX):
            continue
        if path in seen:
            raise InventoryError(f"duplicate Git path: {path!r}")
        if root is not None and not (root / Path(*parts)).is_file():
            raise InventoryError(f"inventory path is missing from the worktree: {path}")
        seen.add(path)
        normalized.append(path)
    return sorted(normalized, key=natural_path_key)


def git_inventory(root: Path = ROOT) -> list[str]:
    """Read the NUL-delimited tracked plus non-ignored-untracked inventory."""
    try:
        result = subprocess.run(
            GIT_LS_FILES_ARGS,
            cwd=root,
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
    except (OSError, subprocess.CalledProcessError) as exc:
        detail = getattr(exc, "stderr", b"")
        if isinstance(detail, bytes):
            detail = detail.decode("utf-8", errors="replace")
        raise InventoryError(f"cannot read Git inventory: {detail or exc}") from exc
    try:
        paths = [item.decode("utf-8") for item in result.stdout.split(b"\0") if item]
    except UnicodeDecodeError as exc:
        raise InventoryError(f"Git inventory contains a non-UTF-8 path: {exc}") from exc
    return normalize_inventory(paths, root=root)


def build_tree(paths: list[str]) -> dict[str, object]:
    tree: dict[str, object] = {}
    for path in paths:
        node = tree
        parts = path.split("/")
        for part in parts[:-1]:
            existing = node.setdefault(part, {})
            if not isinstance(existing, dict):
                raise InventoryError(f"path is both file and directory: {path!r}")
            node = existing
        leaf = parts[-1]
        if leaf in node:
            raise InventoryError(f"path collision while rendering: {path!r}")
        node[leaf] = None
    return tree


def render_tree(paths: list[str]) -> str:
    """Render an exact POSIX tree with natural ordering."""
    canonical = normalize_inventory(list(paths))
    tree = build_tree(canonical)
    tick = chr(96)
    lines = [
        "# GCT Codebase Structure\n",
        "\n",
        f"This file is generated by {tick}build_scripts/manage_codebase_structure.py{tick}. ",
        f"Its authority is {tick}git ls-files --cached --others --exclude-standard -z{tick}; ",
        f"only {tick}_audit_workspace/**{tick} is removed after Git enumeration. ",
        "Every remaining tracked or non-ignored untracked file appears exactly once.\n",
        "\n",
        f"{tick}{tick}{tick}text\n",
        ".\n",
    ]

    def emit(node: dict[str, object], prefix: str) -> None:
        names = sorted(node, key=natural_component_key)
        for index, name in enumerate(names):
            last = index == len(names) - 1
            child = node[name]
            connector = "└── " if last else "├── "
            directory = isinstance(child, dict)
            lines.append(f"{prefix}{connector}{name}{'/' if directory else ''}\n")
            if directory:
                emit(child, prefix + ("    " if last else "│   "))

    emit(tree, "")
    lines.append(f"{tick}{tick}{tick}\n")
    return "".join(lines)


TREE_LINE = re.compile(r"^((?:│   |    )*)(?:├── |└── )(.+)$")


def parse_rendered_paths(document: str) -> list[str]:
    """Recover every leaf path for exact-set validation."""
    tick = chr(96)
    blocks = re.findall(
        re.escape(tick * 3 + "text\n") + r"(.*?)" + re.escape(tick * 3),
        document,
        flags=re.DOTALL,
    )
    if len(blocks) != 1:
        raise InventoryError(f"CODEBASE_STRUCTURE must contain one text tree, found {len(blocks)}")
    lines = blocks[0].splitlines()
    if not lines or lines[0] != ".":
        raise InventoryError("CODEBASE_STRUCTURE tree must start at '.'")
    directories: list[str] = []
    files: list[str] = []
    for line in lines[1:]:
        match = TREE_LINE.fullmatch(line)
        if not match:
            raise InventoryError(f"malformed tree line: {line!r}")
        indent, label = match.groups()
        depth = len(indent) // 4
        if depth > len(directories):
            raise InventoryError(f"tree skips a directory level: {line!r}")
        directories = directories[:depth]
        if label.endswith("/"):
            name = label[:-1]
            if not name:
                raise InventoryError("empty directory label")
            directories.append(name)
        else:
            files.append("/".join([*directories, label]))
    return normalize_inventory(files)


def compare_path_sets(document: str, authority: list[str]) -> tuple[list[str], list[str]]:
    rendered = set(parse_rendered_paths(document))
    expected = set(normalize_inventory(list(authority)))
    return (
        sorted(expected - rendered, key=natural_path_key),
        sorted(rendered - expected, key=natural_path_key),
    )


def check_workflow() -> None:
    workflow = WORKFLOW_PATH.read_text(encoding="utf-8")
    if workflow.count(WORKFLOW_COMMAND) != 1:
        raise InventoryError("audit workflow must invoke the structure check exactly once")


def check_structure() -> int:
    authority = git_inventory()
    expected = render_tree(authority)
    actual = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.is_file() else ""
    missing, extra = compare_path_sets(actual, authority) if actual else (authority, [])
    if missing or extra:
        print("ERROR CODEBASE_STRUCTURE path set differs from Git inventory", file=sys.stderr)
        for path in missing:
            print(f"  MISSING {path}", file=sys.stderr)
        for path in extra:
            print(f"  EXTRA   {path}", file=sys.stderr)
        return 1
    if actual != expected:
        print("ERROR CODEBASE_STRUCTURE ordering or generated prose is stale", file=sys.stderr)
        for line in difflib.unified_diff(
            actual.splitlines(), expected.splitlines(),
            fromfile="CODEBASE_STRUCTURE.md", tofile="expected generated inventory", n=2,
        ):
            print(line, file=sys.stderr)
        return 1
    check_workflow()
    print(f"PASS CODEBASE_STRUCTURE exact Git inventory ({len(authority)} files)")
    return 0


def write_structure() -> int:
    authority = git_inventory()
    check_workflow()
    OUTPUT_PATH.write_text(render_tree(authority), encoding="utf-8", newline="\n")
    print(f"Updated CODEBASE_STRUCTURE.md with {len(authority)} files")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate CODEBASE_STRUCTURE.md")
    mode.add_argument("--check", action="store_true", help="verify exact paths and bytes without writing")
    args = parser.parse_args(argv)
    return write_structure() if args.write else check_structure()


if __name__ == "__main__":
    raise SystemExit(main())
